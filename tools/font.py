for c in chars:
    assert c in G, c

# encode: per glyph 7 row bytes (5 bits each) -> hex string of 7*2 chars
enc = ''.join(''.join('%02x' % int(row.replace('.', '0').replace('#', '1'), 2) for row in G[c]) for c in chars)
js = ("/* 5x7 bitmap font (generated by tools/font.py). */\n'use strict';\n"
      "const Font = (() => {\n"
      "  const CHARS = " + json.dumps(''.join(chars), ensure_ascii=False) + ";\n"
      "  const DATA = '" + enc + "';\n"
      "  const glyphs = {};\n"
      "  for (let i = 0; i < CHARS.length; i++) {\n"
      "    const rows = [];\n"
      "    for (let r = 0; r < 7; r++) rows.push(parseInt(DATA.substr((i * 7 + r) * 2, 2), 16));\n"
      "    glyphs[CHARS[i]] = rows;\n"
      "  }\n"
      "  return { glyphs, W: 5, H: 7 };\n"
      "})();\n")
